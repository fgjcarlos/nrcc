import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const frontendRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const localesRoot = path.join(frontendRoot, 'src', 'locales');
const reportPath = path.resolve(frontendRoot, '..', 'docs', 'i18n-coverage.md');

function flatten(value, prefix = '') {
  const flattened = {};
  for (const [key, child] of Object.entries(value)) {
    const fullKey = prefix ? `${prefix}.${key}` : key;
    if (child && typeof child === 'object' && !Array.isArray(child)) {
      Object.assign(flattened, flatten(child, fullKey));
    } else {
      flattened[fullKey] = String(child ?? '');
    }
  }
  return flattened;
}

function readCatalog(locale, namespace) {
  const catalogPath = path.join(localesRoot, locale, `${namespace}.json`);
  try {
    return flatten(JSON.parse(fs.readFileSync(catalogPath, 'utf8')));
  } catch (error) {
    throw new Error(`read ${locale}/${namespace} catalog: ${error instanceof Error ? error.message : String(error)}`);
  }
}

const namespaces = fs.readdirSync(path.join(localesRoot, 'en'))
  .filter((file) => file.endsWith('.json'))
  .map((file) => path.basename(file, '.json'))
  .sort();

const reports = namespaces.map((namespace) => {
  const en = readCatalog('en', namespace);
  const es = readCatalog('es', namespace);
  const enKeys = Object.keys(en).sort();
  const esKeys = Object.keys(es).sort();
  const missing = enKeys.filter((key) => !(key in es));
  const extra = esKeys.filter((key) => !(key in en));
  const empty = enKeys.filter((key) => !(es[key] ?? '').trim());
  const parity = missing.length === 0 && extra.length === 0;
  const translated = enKeys.filter((key) => (es[key] ?? '').trim()).length;

  return {
    namespace,
    enKeys: enKeys.length,
    esKeys: esKeys.length,
    parity,
    empty,
    coverage: enKeys.length === 0 ? 100 : (translated / enKeys.length) * 100,
  };
});

const allPassing = reports.every((report) => report.parity && report.empty.length === 0 && report.coverage === 100);
const totalEnKeys = reports.reduce((sum, report) => sum + report.enKeys, 0);
const totalTranslated = reports.reduce((sum, report) => sum + Math.round((report.coverage / 100) * report.enKeys), 0);
const overallCoverage = totalEnKeys === 0 ? 100 : (totalTranslated / totalEnKeys) * 100;
const table = reports.map((report) =>
  `| ${report.namespace} | ${report.enKeys} | ${report.esKeys} | ${report.parity ? '100%' : 'mismatch'} | ${report.empty.length} | ${report.coverage.toFixed(0)}% |`,
).join('\n');

const markdown = `# i18n catalog coverage\n\nGenerated by \`pnpm i18n:coverage\`. English is the canonical key set.\n\n| Namespace | EN keys | ES keys | Key parity | Empty ES values | ES coverage |\n| --- | ---: | ---: | --- | ---: | ---: |\n${table}\n\n**Overall:** ${overallCoverage.toFixed(0)}% ES coverage (${totalTranslated}/${totalEnKeys} English keys), ${allPassing ? 'with full key parity and no empty values.' : 'with catalog gaps that must be fixed before merge.'}\n`;

fs.writeFileSync(reportPath, markdown);
console.log(markdown);
if (!allPassing) {
  const failures = reports.filter((report) => !report.parity || report.empty.length > 0 || report.coverage !== 100);
  console.error(`i18n coverage failed for: ${failures.map((report) => report.namespace).join(', ')}`);
  process.exitCode = 1;
}
